package stapel.tools.tokens

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MAP
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec

/** Visibility of a generated tokens declaration. */
public enum class Visibility {
    /** `public` (a library or an app module that exports its theme). */
    Public,

    /** `internal` (an app's own theme). */
    Internal,
}

/**
 * The `compose@1` emitter: renders [ResolvedTokens] as a `stapel.tokens.StapelTokens` value in Kotlin.
 * Refuses a theme that lacks something the typed API has a property for (a canon role, a scale step).
 */
public object ComposeEmitter {
    /** Emitter address in the §68 `<ds>@<version>` form. */
    public const val ADDRESS: String = "compose@1"

    private const val PKG = "stapel.tokens"
    private val STAPEL_TOKENS = ClassName(PKG, "StapelTokens")
    private val ARGB = ClassName(PKG, "Argb")

    /** One file holding `<visibility> val <name>: StapelTokens`. */
    public fun render(resolved: ResolvedTokens, packageName: String, name: String, visibility: Visibility): FileSpec =
        FileSpec.builder(packageName, name)
            .addFileComment(header(resolved))
            .addProperty(
                PropertySpec.builder(name, STAPEL_TOKENS)
                    .addModifiers(modifier(visibility))
                    .addKdoc("The theme generated from `%L` (emitter `%L`).", resolved.sourceId, ADDRESS)
                    .initializer(tokensExpression(resolved))
                    .build(),
            )
            .indent("    ")
            .build()

    /**
     * One file holding `object <objectName>` with one `StapelTokens` property per preset and an `all`
     * map. [presets] maps a preset name to its resolution; [defaultName]'s entry, when present, refers to
     * [defaultReference] instead of repeating it.
     */
    public fun renderPresets(
        presets: Map<String, ResolvedTokens>,
        packageName: String,
        objectName: String,
        visibility: Visibility,
        defaultName: String? = null,
        defaultReference: String? = null,
    ): FileSpec {
        val obj = TypeSpec.objectBuilder(objectName)
            .addModifiers(modifier(visibility))
            .addKdoc("Theme presets: the default theme with each preset's `brand` ramp (the scaffold's `--theme <preset>`).")
        val names = presets.keys.toList()
        for (preset in names) {
            val r = presets.getValue(preset)
            val prop = PropertySpec.builder(identifier(preset), STAPEL_TOKENS).addModifiers(modifier(visibility))
                .addKdoc("Preset `%L` (`%L`).", preset, r.sourceId)
            if (preset == defaultName && defaultReference != null) {
                prop.initializer("%L", defaultReference)
            } else {
                prop.initializer(tokensExpression(r))
            }
            obj.addProperty(prop.build())
        }
        obj.addProperty(
            PropertySpec.builder("all", MAP.parameterizedBy(STRING, STAPEL_TOKENS)).addModifiers(modifier(visibility))
                .addKdoc("Every preset by name, in source order.")
                .initializer(
                    CodeBlock.builder().add("mapOf(\n⇥").apply {
                        names.forEach { add("%S to %L,\n", it, identifier(it)) }
                    }.add("⇤)").build(),
                )
                .build(),
        )
        return FileSpec.builder(packageName, objectName)
            .addFileComment(header(presets.values.first()))
            .addType(obj.build())
            .indent("    ")
            .build()
    }

    private fun header(r: ResolvedTokens) =
        "Generated by tools/tokens-gen (emitter $ADDRESS) from ${r.sourceId}. Do not edit: regenerate with `./gradlew stapelGenerate`."

    private fun modifier(v: Visibility) = if (v == Visibility.Public) KModifier.PUBLIC else KModifier.INTERNAL

    private fun identifier(name: String): String {
        val parts = name.split('-', '_').filter { it.isNotEmpty() }
        return parts.first() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }
    }

    private fun missing(what: String): Nothing =
        throw ThemeException(ThemeProblem("compose-missing", "tokens: $ADDRESS needs $what, which the resolved theme lacks", ThemeProblem.Severity.Error))

    private fun f(d: Double): String = if (d == kotlin.math.floor(d) && kotlin.math.abs(d) < 1e15) "${d.toLong()}f" else "${d}f"

    private fun argb(hex: String): CodeBlock {
        var h = hex.removePrefix("#")
        val alpha = if (h.length == 8) h.substring(6) else "ff"
        h = h.substring(0, 6)
        return CodeBlock.of("%T(0x%Lu)", ARGB, (alpha + h).uppercase())
    }

    private fun camel(key: String): String = identifier(key)

    /** The `StapelTokens(...)` constructor call for [r]. */
    public fun tokensExpression(r: ResolvedTokens): CodeBlock {
        val b = CodeBlock.builder().add("%T(\n⇥", STAPEL_TOKENS)
        for (mode in listOf("light", "dark")) {
            b.add("%L = %T(\n⇥", mode, ClassName(PKG, "ColorTokens"))
            for (role in TokenResolver.CANON_ROLE_ORDER) {
                val c = r.colors[role] ?: missing("role \"$role\"")
                b.add("%L = %L,\n", camel(role), argb(if (mode == "light") c.light else c.dark))
            }
            val extras = r.roleOrder.filter { it !in TokenResolver.CANON_ROLE_ORDER }
            if (extras.isNotEmpty()) {
                b.add("extra = mapOf(\n⇥")
                extras.forEach { role ->
                    val c = r.colors.getValue(role)
                    b.add("%S to %L,\n", role, argb(if (mode == "light") c.light else c.dark))
                }
                b.add("⇤),\n")
            }
            b.add("⇤),\n")
        }
        fun stack(k: String) = r.fontFamily[k] ?: missing("scales.fontFamily.$k")
        b.add("fontFamily = %T(sans = listOf(%L), mono = listOf(%L)),\n", ClassName(PKG, "FontFamilies"),
            stack("sans").joinToString(", ") { CodeBlock.of("%S", it).toString() },
            stack("mono").joinToString(", ") { CodeBlock.of("%S", it).toString() })
        b.add("fontSize = %T(\n⇥", ClassName(PKG, "TypeScale"))
        listOf("xs" to "xs", "sm" to "sm", "md" to "md", "lg" to "lg", "xl" to "xl", "xxl" to "2xl", "xxxl" to "3xl").forEach { (p, k) ->
            val s = r.fontSize[k] ?: missing("scales.fontSize.$k")
            b.add("%L = %T(fontSize = %L, lineHeight = %L),\n", p, ClassName(PKG, "TypeStep"), f(s.fontSize), f(s.lineHeight))
        }
        b.add("⇤),\n")
        fun w(k: String) = r.fontWeight[k] ?: missing("scales.fontWeight.$k")
        b.add("fontWeight = %T(regular = %L, medium = %L, semibold = %L, bold = %L),\n", ClassName(PKG, "FontWeights"),
            w("regular"), w("medium"), w("semibold"), w("bold"))
        b.add("spacing = %T(%L),\n", ClassName(PKG, "SpacingScale"),
            (0..8).joinToString(", ") { "s$it = ${f(r.spacing["$it"] ?: missing("scales.spacing.$it"))}" })
        b.add("radii = %T(%L),\n", ClassName(PKG, "RadiusScale"),
            listOf("none", "sm", "md", "lg", "xl", "full").joinToString(", ") { "$it = ${f(r.radii[it] ?: missing("scales.radii.$it"))}" })
        b.add("controls = %T(height = %L, heightPhone = %L),\n", ClassName(PKG, "ControlTokens"),
            f(r.controls["height"] ?: missing("scales.controls.height")), f(r.controls["height-phone"] ?: missing("scales.controls.height-phone")))
        b.add("breakpoints = %T(%L),\n", ClassName(PKG, "Breakpoints"),
            listOf("phone", "tablet", "desktop").joinToString(", ") { "$it = ${f(r.breakpoints[it] ?: missing("scales.breakpoints.$it"))}" })
        fun responsive(role: String): CodeBlock {
            val v = r.responsive[role] ?: missing("scales.responsive.$role")
            return CodeBlock.of("%T(%L)", ClassName(PKG, "Responsive"),
                listOf("phone", "tablet", "desktop").joinToString(", ") { "$it = ${f(v[it] ?: missing("scales.responsive.$role.$it"))}" })
        }
        b.add("responsive = %T(\n⇥pageGutter = %L,\n", ClassName(PKG, "ResponsiveTokens"), responsive("page-gutter"))
        val extraResponsive = r.responsive.keys.filter { it != "page-gutter" }.sorted()
        if (extraResponsive.isNotEmpty()) {
            b.add("extra = mapOf(\n⇥")
            extraResponsive.forEach { b.add("%S to %L,\n", it, responsive(it)) }
            b.add("⇤),\n")
        }
        b.add("⇤),\n")
        fun shadow(s: ResolvedShadow?): CodeBlock = if (s == null) CodeBlock.of("null") else
            CodeBlock.of("%T(x = %L, y = %L, blur = %L, spread = %L, color = %L)", ClassName(PKG, "Shadow"),
                f(s.x), f(s.y), f(s.blur), f(s.spread), argb(s.color))
        b.add("elevation = %T(\n⇥", ClassName(PKG, "ElevationScale"))
        listOf("none", "low", "medium", "high").forEach { step ->
            val (l, d) = r.elevation[step] ?: missing("elevation.$step")
            b.add("%L = %T(light = %L, dark = %L),\n", step, ClassName(PKG, "Themed"), shadow(l), shadow(d))
        }
        b.add("⇤),\n")
        b.add("sourceId = %S,\n", r.sourceId)
        return b.add("⇤)").build()
    }
}
