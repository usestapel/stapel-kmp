// The PII vectors shared with @stapel/analytics (pii-vectors.json, verdicts of the web guard) are
// embedded into the common test sources, so PiiVectorsTest replays them on jvm, Android host and iOS.
val embedPiiVectors = tasks.register("embedPiiVectors") {
    val source = layout.projectDirectory.file("pii-vectors.json")
    val out = layout.buildDirectory.dir("generated/piiVectors")
    inputs.file(source).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("stapel/analytics")
        dir.deleteRecursively()
        dir.mkdirs()
        val dollar = "$"
        val text = source.asFile.readText().replace(dollar, "$dollar{'$dollar'}")
        dir.resolve("PiiVectorsData.kt").writeText(
            "// Generated by :stapel-analytics:embedPiiVectors from pii-vectors.json. Do not edit.\npackage stapel.analytics\n\n" +
                "internal const val PII_VECTORS_JSON: String = \"\"\"$text\"\"\"\n",
        )
    }
}

kotlin.sourceSets.named("commonTest") { kotlin.srcDir(embedPiiVectors) }
