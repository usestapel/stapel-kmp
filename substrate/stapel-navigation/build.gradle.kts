// The shared route-plan fixtures (src/commonTest/resources/route_plan, produced by stapel-tools'
// planner, see the README there) are embedded into the common test sources, so the same JSON is
// replayed on jvm, Android host and the iOS simulator without any file-system access from tests.
val embedRoutePlanFixtures by tasks.registering {
    val source = layout.projectDirectory.dir("src/commonTest/resources/route_plan")
    val out = layout.buildDirectory.dir("generated/routePlanFixtures")
    inputs.files(fileTree(source) { include("*.json") }).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("stapel/navigation")
        dir.deleteRecursively()
        dir.mkdirs()
        val files = source.asFile.listFiles { f -> f.extension == "json" && f.name != "index.json" }!!.sortedBy { it.name }
        val dollar = "$"
        val body = files.joinToString("\n") { f ->
            val chunks = f.readText().replace(dollar, "$dollar{'$dollar'}").chunked(16_000)
            "    \"${f.nameWithoutExtension}\" to listOf(\n" +
                chunks.joinToString(",\n") { "        \"\"\"$it\"\"\"" } + ",\n    ).joinToString(\"\"),"
        }
        // One route type per fixture destination id: resolveNav binds each route type to one id.
        @Suppress("UNCHECKED_CAST")
        val ids = files.flatMap { f ->
            val case = groovy.json.JsonSlurper().parse(f) as Map<String, Any?>
            (case["input"] as List<Map<String, Any?>>).flatMap { pair ->
                (pair["nav"] as List<Map<String, Any?>>).map { it["id"] as String }
            }
        }.toSortedSet()
        val routes = ids.withIndex().joinToString("\n") { (i, id) ->
            "@kotlinx.serialization.Serializable internal data object FxRoute$i : Route { override fun toString(): String = \"$id\" }"
        }
        val table = ids.withIndex().joinToString("\n") { (i, id) ->
            "    \"$id\" to FixtureRouteType(FxRoute$i::class, FxRoute$i.serializer(), FxRoute$i),"
        }
        dir.resolve("RoutePlanFixtureRoutes.kt").writeText(
            "// Generated by :stapel-navigation:embedRoutePlanFixtures.\npackage stapel.navigation\n\n$routes\n\n" +
                "internal val FIXTURE_ROUTES: Map<String, FixtureRouteType<*>> = mapOf(\n$table\n)\n",
        )
        dir.resolve("RoutePlanFixtureData.kt").writeText(
            "// Generated by :stapel-navigation:embedRoutePlanFixtures from src/commonTest/resources/route_plan.\n" +
                "package stapel.navigation\n\ninternal val ROUTE_PLAN_FIXTURES: Map<String, String> = mapOf(\n$body\n)\n",
        )
    }
}

kotlin.sourceSets.named("commonTest") { kotlin.srcDir(embedRoutePlanFixtures) }
