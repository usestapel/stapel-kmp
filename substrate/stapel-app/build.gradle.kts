// The vendored, digest-pinned stapel-tools composition data (gradle/composition: composition-registry.json
// and the route-plan fixtures of the same wheel) is embedded into the common test sources, so
// PinnedRoutePlanTest replays the planner's plans through resolveNav on jvm, Android host and iOS.
val embedPinnedRoutePlans = tasks.register("embedPinnedRoutePlans") {
    val source = rootProject.layout.projectDirectory.dir("gradle/composition")
    val out = layout.buildDirectory.dir("generated/pinnedRoutePlans")
    inputs.files(fileTree(source) { include("**/*.json") }).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("stapel/app")
        dir.deleteRecursively()
        dir.mkdirs()
        val root = source.asFile
        val files = root.walkTopDown().filter { it.isFile && it.extension == "json" && it.name != "pin.json" }.sortedBy { it.path }.toList()
        val dollar = "$"
        fun literal(text: String) = text.replace(dollar, "$dollar{'$dollar'}").chunked(16_000)
            .joinToString(",\n") { "        \"\"\"$it\"\"\"" }
        val body = files.joinToString("\n") { f ->
            "    \"${f.relativeTo(root).invariantSeparatorsPath}\" to listOf(\n${literal(f.readText())},\n    ).joinToString(\"\"),"
        }
        @Suppress("UNCHECKED_CAST")
        val registry = groovy.json.JsonSlurper().parse(root.resolve("composition-registry.json")) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val ids = (registry["bricks"] as Map<String, Map<String, Any?>>).values
            .flatMap { b -> (b["nav"] as List<Map<String, Any?>>).map { it["id"] as String } }.toSortedSet()
        val routes = ids.withIndex().joinToString("\n") { (i, id) ->
            "@kotlinx.serialization.Serializable internal data object PinRoute$i : stapel.navigation.Route { override fun toString(): String = \"$id\" }"
        }
        val table = ids.withIndex().joinToString("\n") { (i, id) -> "    \"$id\" to PinRouteType(PinRoute$i::class, PinRoute$i.serializer(), PinRoute$i)," }
        dir.resolve("PinnedCompositionData.kt").writeText(
            "// Generated by :stapel-app:embedPinnedRoutePlans from gradle/composition. Do not edit.\npackage stapel.app\n\n" +
                "internal val PINNED_COMPOSITION: Map<String, String> = mapOf(\n$body\n)\n\n$routes\n\n" +
                "internal class PinRouteType<R : stapel.navigation.Route>(val type: kotlin.reflect.KClass<R>, val serializer: kotlinx.serialization.KSerializer<R>, val instance: R)\n\n" +
                "internal val PINNED_ROUTES: Map<String, PinRouteType<*>> = mapOf(\n$table\n)\n",
        )
    }
}

kotlin.sourceSets.named("commonTest") { kotlin.srcDir(embedPinnedRoutePlans) }
