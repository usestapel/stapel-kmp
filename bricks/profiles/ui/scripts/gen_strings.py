#!/usr/bin/env python3
"""Writes ProfilesWebStrings.kt from the web pair's string tables.

Usage: gen_strings.py <stapel-react checkout> <output .kt>

Reads packages/profiles-react/src/i18n/keys.ts (English) and ru.ts (Russian) of @stapel/profiles-react,
keeps every `profiles.*` UI key (error codes come from the backend catalogs instead), and writes the
typed keys (`ProfilesStrings`, a PluralKey for every family with `.one`/`.other`) and the two
dictionaries. The checkout's commit is written into the header; StringsTest holds the output to the
rules (every English key has a Russian one, plural families complete, placeholders equal).
"""
import json
import re
import subprocess
import sys

PLURAL_SUFFIXES = ("one", "few", "many", "other", "two", "zero")


def parse(path):
    text = open(path, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r'"(profiles\.[a-zA-Z0-9_.]+)":\s*\n?\s*("(?:[^"\\]|\\.)*"|`[^`]*`)\s*,', text):
        raw = m.group(2)
        out[m.group(1)] = json.loads(raw) if raw.startswith('"') else raw[1:-1]
    return out


def kotlin_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def ident(key):
    parts = re.split(r"[._]", key.removeprefix("profiles."))
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return name


def main():
    repo, out = sys.argv[1], sys.argv[2]
    base = f"{repo}/packages/profiles-react/src/i18n"
    en, ru = parse(f"{base}/keys.ts"), parse(f"{base}/ru.ts")
    ref = subprocess.check_output(["git", "-C", repo, "rev-parse", "HEAD"], text=True).strip()
    plural_families = sorted({k.rsplit(".", 1)[0] for k in en if k.rsplit(".", 1)[-1] in PLURAL_SUFFIXES and k.endswith(".other")})
    singles = sorted(k for k in en if not any(k == f"{p}.{s}" for p in plural_families for s in PLURAL_SUFFIXES))
    lines = [
        "// Generated by bricks/profiles/ui/scripts/gen_strings.py — DO NOT EDIT.",
        f"// Source: stapel-react packages/profiles-react/src/i18n (keys.ts, ru.ts) @ {ref[:12]}",
        "package stapel.profiles.ui",
        "",
        "import stapel.i18n.PluralKey",
        "import stapel.i18n.StringKey",
        "",
        "/**",
        " * Typed keys of the copy this library shares with the web pair (`@stapel/profiles-react`): one",
        " * translation override applies to both platforms. Mobile-only copy lives in [ProfilesUiStrings].",
        " */",
        "public object ProfilesStrings {",
    ]
    for k in singles:
        lines += [f"    /** {kotlin_doc(en[k])} */", f"    public val {ident(k)}: StringKey = StringKey({kotlin_string(k)})", ""]
    for k in plural_families:
        lines += [f"    /** {kotlin_doc(en[k + '.other'])} (plural) */", f"    public val {ident(k)}: PluralKey = PluralKey({kotlin_string(k)})", ""]
    lines[-1:] = ["}", ""]
    for name, table in (("PROFILES_WEB_EN", en), ("PROFILES_WEB_RU", ru)):
        lines.append(f"internal val {name}: Map<String, String> = mapOf(")
        for k in sorted(table):
            lines.append(f"    {kotlin_string(k)} to {kotlin_string(table[k])},")
        lines += [")", ""]
    open(out, "w", encoding="utf-8").write("\n".join(lines).rstrip() + "\n")


def kotlin_doc(s):
    return s.replace("*/", "* /").replace("\n", " ")


if __name__ == "__main__":
    main()
