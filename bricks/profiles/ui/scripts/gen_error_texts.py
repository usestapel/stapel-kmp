#!/usr/bin/env python3
"""Writes ProfilesErrorTextsRu.kt from stapel-profiles's translations/errors.ru.json.

Usage: gen_error_texts.py <stapel-profiles checkout at the pinned ref> <contracts/profiles/errors.json> <output .kt>

Codes the pinned errors.json does not declare are dropped and printed (a stale backend translation).

The checkout must be at the commit named in contracts/profiles/pin.json; the commit and the sha256 of the
source file are written into the header, and ErrorTextsTest checks the output against the
domain's ProfilesErrorCatalog (every key is a known code, the {param} sets match the English template).
"""
import hashlib
import json
import subprocess
import sys


def kotlin_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def main() -> None:
    repo, contract, out = sys.argv[1], sys.argv[2], sys.argv[3]
    known = {entry["code"] for entry in json.load(open(contract))}
    path = f"{repo}/translations/errors.ru.json"
    raw = open(path, "rb").read()
    entries = json.loads(raw)
    ref = subprocess.check_output(["git", "-C", repo, "rev-parse", "HEAD"], text=True).strip()
    lines = [
        "// Generated by bricks/profiles/ui/scripts/gen_error_texts.py — DO NOT EDIT.",
        f"// Source: stapel-profiles translations/errors.ru.json @ {ref[:12]} | sha256:{hashlib.sha256(raw).hexdigest()[:12]}",
        "package stapel.profiles.ui",
        "",
        "import stapel.result.ErrorCode",
        "import stapel.result.text.ErrorCatalog",
        "import stapel.result.text.ErrorSpec",
        "import stapel.result.text.LocaleTag",
        "",
        "/**",
        " * Russian texts of `stapel-profiles`'s error codes, from the backend's own locale catalog. Codes the",
        " * backend has not translated are absent here and fall through the error-text ladder (server text in",
        " * the same language, then the status floor). Register after the app's own catalogs: see [profilesErrorCatalogs].",
        " */",
        "public object ProfilesErrorTextsRu : ErrorCatalog {",
        "    /** `profiles`: the brick these texts belong to. */",
        '    override val owner: String = "profiles"',
        "",
        "    /** Every code this catalog translates. */",
        "    public val codes: Set<String> get() = TEXTS.keys",
        "",
        "    /** Always null: the contract entries come from the domain's `ProfilesErrorCatalog`. */",
        "    override fun spec(code: ErrorCode): ErrorSpec? = null",
        "",
        "    /** The Russian template for [code], only for the `ru` tag (the resolver walks `ru-RU` → `ru` → `en`). */",
        '    override fun template(code: ErrorCode, locale: LocaleTag): String? = if (locale.value == "ru") TEXTS[code.value] else null',
        "",
        "    private val TEXTS: Map<String, String> = mapOf(",
    ]
    stale = sorted(c for c in entries if c not in known)
    for c in stale:
        print(f"dropped (not in the pinned errors.json): {c}", file=sys.stderr)
    for code in sorted(c for c in entries if c in known):
        lines.append(f"        {kotlin_string(code)} to {kotlin_string(entries[code])},")
    lines += ["    )", "}", ""]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
