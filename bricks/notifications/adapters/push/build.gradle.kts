// --- push payload types: contracts/notifications/push.json (JSON Schema, pinned) -> NotificationPushPayload.kt ---
// Generated at build time from the vendored file whose sha256 pin.json records; nothing generated is
// committed, so the types cannot drift from the pin. The generator knows exactly the shapes push.json v1
// uses (object, string, integer, string enum, string const, a $ref to the string map PushData) and fails
// the build on anything else, so a contract change it cannot express is a red build, not a silent gap.
val generatePushPayload = tasks.register("generatePushPayload") {
    val schemaFile = rootProject.layout.projectDirectory.file("contracts/notifications/push.json")
    val out = layout.buildDirectory.dir("generated/pushPayload")
    inputs.file(schemaFile).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(out)
    doLast {
        @Suppress("UNCHECKED_CAST")
        val root = groovy.json.JsonSlurper().parse(schemaFile.asFile) as Map<String, Any?>
        val sha = MessageDigest.getInstance("SHA-256").digest(schemaFile.asFile.readBytes())
            .joinToString("") { "%02x".format(it) }
        fun camel(wire: String) = wire.split('_').mapIndexed { i, p -> if (i == 0) p else p.replaceFirstChar { it.uppercase() } }.joinToString("")
        fun pascal(wire: String) = camel(wire).replaceFirstChar { it.uppercase() }
        fun doc(text: Any?) = (text as? String)?.replace("*/", "*&#47;")?.replace("\n", " ") ?: "See the push contract."
        fun str(text: String) = "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        @Suppress("UNCHECKED_CAST")
        val defs = root["\$defs"] as Map<String, Map<String, Any?>>
        @Suppress("UNCHECKED_CAST")
        val data = defs.getValue("PushData")
        check(data["type"] == "object") { "push.json: PushData is not an object" }
        @Suppress("UNCHECKED_CAST")
        val dataProps = data["properties"] as Map<String, Map<String, Any?>>
        @Suppress("UNCHECKED_CAST")
        val dataRequired = (data["required"] as List<String>).toSet()
        val b = StringBuilder()
        b.append("// Generated by :stapel-notifications-push:generatePushPayload from contracts/notifications/push.json\n")
        b.append("// (sha256 $sha). Do not edit.\n")
        b.append("package stapel.notifications.push\n\n")
        b.append("import kotlinx.serialization.SerialName\nimport kotlinx.serialization.Serializable\n\n")
        // Enums of PushData (string enums become sealed-free enums with an Unknown fallback for forward compatibility).
        val enums = mutableMapOf<String, List<String>>()
        for ((wire, p) in dataProps) {
            check(p["type"] == "string") { "push.json: PushData.$wire is ${p["type"]}, only strings are generated" }
            @Suppress("UNCHECKED_CAST")
            (p["enum"] as List<String>?)?.let { enums[wire] = it }
        }
        for ((wire, values) in enums) {
            val name = "NotificationPush" + pascal(wire)
            b.append("/** ${doc(dataProps.getValue(wire)["description"])} */\n")
            b.append("public enum class $name(\n    /** The wire value. */\n    public val wire: String,\n) {\n")
            for (v in values) b.append("    /** `$v`. */\n    ${pascal(v)}(${str(v)}),\n\n")
            b.append("    /** A value this client version does not know. */\n    Unknown(\"\"),\n    ;\n\n")
            b.append("    /** Holder of [of]. */\n    public companion object {\n")
            b.append("        /** The value for [wire]; [Unknown] for anything else. */\n")
            b.append("        public fun of(wire: String): $name = entries.firstOrNull { it != Unknown && it.wire == wire } ?: Unknown\n    }\n}\n\n")
        }
        b.append("/**\n * ${doc(data["description"])} Typed view of a push message's `data` map (`\$defs.PushData`).\n *\n")
        for ((wire, _) in dataProps) b.append(" * @property ${camel(wire)} `$wire`.\n")
        b.append(" * @property extras every other key of the map (all values strings).\n */\n")
        b.append("public data class NotificationPushData(\n")
        for ((wire, p) in dataProps) {
            val type = if (wire in enums) "NotificationPush" + pascal(wire) else "String"
            val optional = wire !in dataRequired
            val deprecated = p["deprecated"] == true
            if (deprecated) b.append("    @Deprecated(${str(doc(p["description"]))})\n")
            b.append("    public val ${camel(wire)}: $type${if (optional) "? = null" else ""},\n")
        }
        b.append("    public val extras: Map<String, String> = emptyMap(),\n) {\n")
        b.append("    /** Holder of [parse]. */\n    public companion object {\n")
        b.append("        /** The keys the contract names. */\n")
        b.append("        public val KNOWN_KEYS: Set<String> = setOf(${dataProps.keys.joinToString { str(it) }})\n\n")
        b.append("        /**\n         * Reads [data]; null when a required key is absent")
        dataProps.entries.firstOrNull { it.value["const"] != null }?.let { b.append(" or `${it.key}` is not `${it.value["const"]}`") }
        b.append(" (another contract version).\n         */\n")
        b.append("        @Suppress(\"DEPRECATION\")\n")
        b.append("        public fun parse(data: Map<String, String>): NotificationPushData? {\n")
        for (wire in dataRequired) b.append("            val ${camel(wire)} = data[${str(wire)}] ?: return null\n")
        for ((wire, p) in dataProps) p["const"]?.let { b.append("            if (${camel(wire)} != ${str(it as String)}) return null\n") }
        b.append("            return NotificationPushData(\n")
        for ((wire, _) in dataProps) {
            val value = if (wire in dataRequired) camel(wire) else "data[${str(wire)}]"
            val typed = if (wire in enums) {
                if (wire in dataRequired) "NotificationPush${pascal(wire)}.of($value)" else "$value?.let { NotificationPush${pascal(wire)}.of(it) }"
            } else value
            b.append("                ${camel(wire)} = $typed,\n")
        }
        b.append("                extras = data.filterKeys { it !in KNOWN_KEYS },\n            )\n        }\n    }\n}\n\n")
        // The message object: title, body, data (string map), android {...}, apns {...}.
        @Suppress("UNCHECKED_CAST")
        val props = root["properties"] as Map<String, Map<String, Any?>>
        fun objectClass(name: String, schema: Map<String, Any?>, indent: String) {
            @Suppress("UNCHECKED_CAST")
            val ps = schema["properties"] as Map<String, Map<String, Any?>>
            @Suppress("UNCHECKED_CAST")
            val req = ((schema["required"] as List<String>?) ?: emptyList()).toSet()
            b.append("$indent/** ${doc(schema["description"])} */\n$indent@Serializable\n${indent}public data class $name(\n")
            val nested = mutableListOf<Pair<String, Map<String, Any?>>>()
            for ((wire, p) in ps) {
                val type = when {
                    p["\$ref"] == "#/\$defs/PushData" -> "Map<String, String>"
                    p["type"] == "string" -> "String"
                    p["type"] == "integer" -> "Long"
                    p["type"] == "object" -> pascal(wire).also { nested += it to p }
                    else -> error("push.json: $name.$wire has an unsupported shape: $p")
                }
                val optional = wire !in req
                b.append("$indent    /** ${doc(p["description"] ?: (p["enum"] as List<*>?)?.joinToString(prefix = "One of: "))} */\n")
                b.append("$indent    @SerialName(${str(wire)})\n")
                b.append("$indent    public val ${camel(wire)}: $type${if (optional) "? = null" else ""},\n")
            }
            b.append("$indent)")
            if (nested.isNotEmpty() || name == "NotificationPushMessage") {
                b.append(" {\n")
                for ((n, s) in nested) objectClass(n, s, "$indent    ")
                if (name == "NotificationPushMessage") {
                    b.append("$indent    /** The typed view of [data]; null when it is not this contract version. */\n")
                    b.append("$indent    public val payload: NotificationPushData? get() = NotificationPushData.parse(data)\n")
                }
                b.append("$indent}\n")
            } else {
                b.append("\n")
            }
            b.append("\n")
        }
        objectClass("NotificationPushMessage", root + mapOf("properties" to props), "")
        b.append("/** The pinned push contract's id and version. */\npublic object NotificationPushContract {\n")
        b.append("    /** `\$id` of push.json. */\n    public const val ID: String = ${str(root["\$id"] as String)}\n")
        b.append("    /** The payload version (`data.v`) this client reads. */\n    public const val VERSION: String = ${str(dataProps.getValue("v")["const"] as String)}\n")
        b.append("    /** sha256 of the push.json the types were generated from. */\n    public const val SHA256: String = ${str(sha)}\n}\n")
        val f = out.get().asFile.resolve("stapel/notifications/push/NotificationPushPayload.kt")
        f.parentFile.mkdirs()
        f.writeText(b.toString())
    }
}
kotlin.sourceSets.named("commonMain") { kotlin.srcDir(generatePushPayload) }
