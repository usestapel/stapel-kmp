/** Main class of the gallery's catalogue tool (`index`, `record`, `verify`, `export`); see showcase/gallery. */
const val SHOWCASE_TOOL_MAIN = "stapel.showcase.gallery.tools.CatalogToolKt"

/** The symbol every catalogue module declares at the top of its package. */
const val STORY_CATALOG_SYMBOL = "storyCatalog"

/** Package of the generated registry inside the gallery. */
const val SHOWCASE_REGISTRY_PACKAGE = "stapel.showcase.gallery.generated"

/**
 * A module that exports a story catalogue: every `bricks/<brick>/demo` and every `showcase/stories/<x>`.
 *
 * @property path Gradle project path.
 * @property dir directory relative to the root (snapshots live in `<dir>/snapshots`).
 * @property packageName the package declaring `val storyCatalog`.
 * @property brick the brick key for demo modules, null for showcase stories.
 */
data class CatalogModule(val path: String, val dir: String, val packageName: String, val brick: String?)

/** Finds the catalogue modules by directory (the settings naming rule), so no list is edited by hand. */
fun discoverCatalogModules(rootDir: File, projects: List<Pair<String, File>>, root: String): List<CatalogModule> =
    projects.mapNotNull { (path, dir) ->
        val rel = dir.relativeTo(rootDir).invariantSeparatorsPath
        val p = rel.split('/')
        when {
            p.size == 3 && p[0] == "bricks" && p[2] == "demo" ->
                CatalogModule(path, rel, "$root.${p[1].replace('-', '.')}.ui.demo", p[1])
            p.size == 3 && p[0] == "showcase" && p[1] == "stories" ->
                CatalogModule(path, rel, "$root.showcase.stories.${p[2].replace('-', '.')}", null)
            else -> null
        }
    }.sortedBy { it.path }

/** The generated registry source for [modules]. */
fun showcaseRegistrySource(modules: List<CatalogModule>): String = buildString {
    appendLine("// Generated by the stapel.showcase-gallery plugin from the catalogue modules (bricks/*/demo, showcase/stories/*).")
    appendLine("// Do not edit: add a module that declares `val $STORY_CATALOG_SYMBOL` and it appears here.")
    appendLine("package $SHOWCASE_REGISTRY_PACKAGE")
    appendLine()
    appendLine("/** A discovered catalogue and the module that exports it. */")
    appendLine("public class DiscoveredCatalog(public val module: String, public val dir: String, public val catalog: stapel.showcase.StoryCatalog)")
    appendLine()
    appendLine("/** Every catalogue module of the repository, in project-path order. */")
    appendLine("public val discoveredCatalogs: List<DiscoveredCatalog> by lazy {")
    appendLine("    listOf(")
    modules.forEach { m ->
        appendLine("        DiscoveredCatalog(\"${m.path}\", \"${m.dir}\", ${m.packageName}.$STORY_CATALOG_SYMBOL),")
    }
    appendLine("    )")
    appendLine("}")
}

/** Writes the gallery's registry from the discovered catalogue modules. */
abstract class GenerateShowcaseRegistry : DefaultTask() {
    /** `path|dir|package|brick` per module. */
    @get:Input abstract val modules: ListProperty<String>

    /** Generated source root. */
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun run() {
        val list = modules.get().map { it.split('|').let { p -> CatalogModule(p[0], p[1], p[2], p[3].ifEmpty { null }) } }
        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val file = File(dir, SHOWCASE_REGISTRY_PACKAGE.replace('.', '/') + "/GeneratedCatalogs.kt")
        file.parentFile.mkdirs()
        file.writeText(showcaseRegistrySource(list))
    }
}

/**
 * `stapel.showcase-gallery`: applied to `showcase/gallery` next to `stapel.showcase`. Adds every
 * catalogue module as a dependency, generates the registry, and registers the tasks that read the
 * catalogues: `exportCatalogIndex`, the gate `checkDemoCoverage`, `recordScreenshots` /
 * `verifyScreenshots` (macOS) and `exportCatalog` (docs).
 */
class ShowcaseGalleryPlugin : Plugin<Project> {
    override fun apply(target: Project) = with(target) {
        if (!pluginManager.hasPlugin("stapel.showcase")) pluginManager.apply(ShowcasePlugin::class.java)
        val kmp = extensions.getByType(KotlinMultiplatformExtension::class.java)
        val root = packageRoot(this)
        val modules = discoverCatalogModules(rootDir, rootProject.subprojects.map { it.path to it.projectDir }, root)
        val common = kmp.sourceSets.getByName("commonMain")
        common.dependencies {
            rootProject.findProject(":stapel-showcase")?.let { implementation(project(it.path)) }
            modules.forEach { implementation(project(it.path)) }
        }
        val registry = tasks.register("generateShowcaseRegistry", GenerateShowcaseRegistry::class.java) {
            group = "stapel generate"
            description = "Generates the gallery's catalogue registry from bricks/*/demo and showcase/stories/*."
            this.modules.set(modules.map { "${it.path}|${it.dir}|${it.packageName}|${it.brick ?: ""}" })
            outputDir.set(layout.buildDirectory.dir("generated/stapel/showcaseRegistry"))
        }
        common.kotlin.srcDir(registry.map { it.outputDir })

        val jvmMain = kmp.jvm().compilations.getByName("main")
        val toolClasspath = files(jvmMain.output.allOutputs, jvmMain.runtimeDependencyFiles)
        val repoRoot = rootDir.absolutePath
        fun JavaExec.tool(vararg args: String) {
            classpath = toolClasspath
            mainClass.set(SHOWCASE_TOOL_MAIN)
            args(*args)
            dependsOn(jvmMain.compileTaskProvider)
            // Pinned so renders do not depend on the machine's settings (font policy: macOS only, see the tool).
            jvmArgs("-Djava.awt.headless=true", "-Duser.language=en", "-Duser.country=US", "-Duser.timezone=UTC", "-Dfile.encoding=UTF-8")
        }
        val indexFile = layout.buildDirectory.file("showcase/catalog-index.json")
        val index = tasks.register("exportCatalogIndex", JavaExec::class.java) {
            group = "stapel showcase"
            description = "Writes build/showcase/catalog-index.json: every catalogue, story, state, knob and coverage claim."
            tool("index", "--out", indexFile.get().asFile.absolutePath)
            outputs.file(indexFile)
        }
        val coverage = tasks.register("checkDemoCoverage", CheckDemoCoverage::class.java) {
            group = STAPEL_GATES
            description = "Every brick UI has a demo catalogue; every screen-table member and every StapelSkin slot has a story."
            this.index.set(index.flatMap { layout.buildDirectory.file("showcase/catalog-index.json") })
            dependsOn(index)
            val brickUiDirs = rootProject.subprojects.map { it.projectDir.relativeTo(rootDir).invariantSeparatorsPath }
                .filter { Regex("bricks/[^/]+/ui").matches(it) }
            brickUis.set(brickUiDirs.map { it.split('/')[1] }.sorted())
            demoBricks.set(modules.mapNotNull { it.brick })
            catalogModules.set(modules.associate { it.path to (it.brick ?: "") })
            uiDump.from(rootProject.file("substrate/stapel-ui/api/jvm/stapel-ui.api"))
            screenDumps.from(brickUiDirs.map { d -> rootProject.file("$d/api/jvm/stapel-${d.split('/')[1]}-ui.api") })
            stamp.set(layout.buildDirectory.file("stapel-gates/checkDemoCoverage"))
        }
        tasks.named("stapelCheckFast").configure { dependsOn(coverage) }
        pluginManager.withPlugin("lifecycle-base") { tasks.named("check").configure { dependsOn(coverage) } }

        val catalogsFilter = providers.gradleProperty("stapel.showcase.catalogs")
        tasks.register("recordScreenshots", JavaExec::class.java) {
            group = "stapel showcase"
            description = "Records <module>/snapshots/*.png for every story × state × {Material3, Foundation} × {light, dark} (macOS only)."
            tool("record", "--root", repoRoot)
            catalogsFilter.orNull?.let { args("--catalogs", it) }
            outputs.upToDateWhen { false }
        }
        val reportDir = layout.buildDirectory.dir("showcase/screenshot-report")
        val verify = tasks.register("verifyScreenshots", JavaExec::class.java) {
            group = "verification"
            description = "Renders every story of each catalogue that has a snapshots/ directory and compares pixel by pixel (macOS only)."
            tool("verify", "--root", repoRoot, "--report", reportDir.get().asFile.absolutePath)
            catalogsFilter.orNull?.let { args("--catalogs", it) }
            val mac = System.getProperty("os.name").startsWith("Mac")
            onlyIf("baselines are recorded and verified on macOS only (text rasterisation differs on Linux)") { mac }
            outputs.upToDateWhen { false }
        }
        tasks.named("stapelCheck").configure { dependsOn(verify) }
        tasks.register("exportCatalog", JavaExec::class.java) {
            group = "stapel showcase"
            description = "Writes build/showcase/catalog: catalog.json + a PNG per story/state/mode for the docs site."
            val out = layout.buildDirectory.dir("showcase/catalog")
            tool("export", "--out", out.get().asFile.absolutePath, "--density", "2")
            outputs.dir(out)
        }
        Unit
    }
}

/**
 * `checkDemoCoverage` (on the gallery): reads the exported catalogue index and the committed ABI dumps.
 * Fails when a brick UI module has no demo catalogue, when a member of a brick's screen table
 * (`interface <Brick>Screens` in its jvm ABI dump) is not covered by a story of that brick's catalogue,
 * when a `StapelSkin` slot (from stapel-ui's dump) is covered by no story, or when catalogue ids clash.
 */
abstract class CheckDemoCoverage : DefaultTask() {
    /** build/showcase/catalog-index.json of the gallery. */
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val index: RegularFileProperty

    /** Brick keys that have a `bricks/<brick>/ui` module. */
    @get:Input abstract val brickUis: ListProperty<String>

    /** Brick keys that have a demo module. */
    @get:Input abstract val demoBricks: ListProperty<String>

    /** Catalogue module path → brick key ("" for showcase stories). */
    @get:Input abstract val catalogModules: MapProperty<String, String>

    /** stapel-ui's jvm ABI dump. */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val uiDump: ConfigurableFileCollection

    /** Each brick UI's jvm ABI dump. */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val screenDumps: ConfigurableFileCollection

    /** Stamp. */
    @get:OutputFile abstract val stamp: RegularFileProperty

    @TaskAction
    @Suppress("UNCHECKED_CAST")
    fun run() {
        val dumpsByName = screenDumps.files.associateBy { it.name }
        val screens = brickUis.get().associateWith { b ->
            dumpsByName["stapel-$b-ui.api"]?.takeIf { it.isFile }?.let { interfaceMembers(it.readText(), screensInterface(b)) }
        }
        val slots = uiDump.files.firstOrNull { it.isFile }?.let { interfaceMembers(it.readText(), STAPEL_SKIN_INTERNAL_NAME) }
        val parsed = JsonSlurper().parse(index.get().asFile) as Map<String, Any?>
        val catalogs = (parsed["catalogs"] as List<Map<String, Any?>>).map { c ->
            IndexedCatalog(
                id = c["id"] as String,
                module = c["module"] as String,
                coverage = (c["stories"] as List<Map<String, Any?>>).associate { s -> (s["id"] as String) to (s["covers"] as List<String>).toSet() },
            )
        }
        val problems = demoCoverageViolations(brickUis.get(), demoBricks.get().toSet(), catalogModules.get(), catalogs, slots, screens)
        if (problems.isNotEmpty()) {
            throw GradleException(
                "checkDemoCoverage failed (docs/adding-a-module.md §7, stories):\n" + problems.joinToString("\n") { "  - $it" },
            )
        }
        stamp.get().asFile.apply { parentFile.mkdirs() }.writeText("ok\n")
    }
}

/** One catalogue of the index: its id, the module exporting it, and story id → covered target keys. */
data class IndexedCatalog(val id: String, val module: String, val coverage: Map<String, Set<String>>)

/** JVM internal name of the skin slot interface in stapel-ui's dump. */
const val STAPEL_SKIN_INTERNAL_NAME = "stapel/ui/skin/StapelSkin"

/** JVM internal name of brick [brick]'s screen table: `stapel/<brick>/ui/<Brick>Screens`. */
fun screensInterface(brick: String): String =
    "stapel/${brick.replace('-', '/')}/ui/" + brick.split('-').joinToString("") { it.replaceFirstChar(Char::uppercaseChar) } + "Screens"

/** Names of the upper-case member functions of interface [internalName] in a jvm ABI dump; null when absent. */
fun interfaceMembers(dump: String, internalName: String): List<String>? {
    val lines = dump.lines()
    val start = lines.indexOfFirst { l ->
        l.startsWith("public abstract interface class $internalName ") || l.startsWith("public abstract interface class $internalName {")
    }
    if (start < 0) return null
    val fn = Regex("""^\s*public (?:abstract )?fun ([A-Z]\w*) \(""")
    return lines.drop(start + 1).takeWhile { it.trim() != "}" }.mapNotNull { fn.find(it)?.groupValues?.get(1) }.distinct().sorted()
}

/**
 * The rule of `checkDemoCoverage`, pure. [slots] null = stapel-ui's dump is missing; a value of
 * [screens] null = that brick UI's dump is missing (an empty list = it has no screen table).
 */
fun demoCoverageViolations(
    brickUis: List<String>,
    demoBricks: Set<String>,
    catalogModules: Map<String, String>,
    catalogs: List<IndexedCatalog>,
    slots: List<String>?,
    screens: Map<String, List<String>?>,
): List<String> {
    val out = mutableListOf<String>()
    catalogs.groupBy { it.id }.filterValues { it.size > 1 }.forEach { (id, list) ->
        out += "catalogue id '$id' is exported by ${list.joinToString { it.module }}: catalogue ids are unique"
    }
    catalogs.filter { it.coverage.isEmpty() }.forEach { out += "catalogue '${it.id}' (${it.module}) has no stories" }
    for (b in brickUis) {
        if (b !in demoBricks) {
            out += "stapel-$b-ui has no demo module: create bricks/$b/demo (id(\"stapel.brick-demo\")) declaring `val $STORY_CATALOG_SYMBOL: StoryCatalog`"
            continue
        }
        val modulePath = catalogModules.entries.firstOrNull { it.value == b }?.key
        val catalog = catalogs.firstOrNull { it.module == modulePath }
        if (catalog == null) {
            out += "bricks/$b/demo exports no catalogue in the index (declare `val $STORY_CATALOG_SYMBOL` in its package)"
            continue
        }
        val table = screens[b]
        if (table == null) {
            out += "bricks/$b/ui/api/jvm/stapel-$b-ui.api is missing: run ./gradlew :stapel-$b-ui:updateKotlinAbi"
            continue
        }
        val covered = catalog.coverage.values.flatten().toSet()
        table.filter { "screen:$it" !in covered }.forEach {
            out += "screen '$it' of ${screensInterface(b).substringAfterLast('/')} has no story in catalogue '${catalog.id}': add a story with covers = setOf(StoryTarget.Screen(\"$it\"))"
        }
    }
    if (slots == null) {
        out += "substrate/stapel-ui/api/jvm/stapel-ui.api is missing or has no StapelSkin: run ./gradlew :stapel-ui:updateKotlinAbi"
    } else {
        val covered = catalogs.flatMap { it.coverage.values.flatten() }.toSet()
        slots.filter { "slot:$it" !in covered }.forEach {
            out += "StapelSkin slot '$it' has no story: add one to showcase/stories/ui with covers = setOf(StoryTarget.Slot(\"$it\"))"
        }
    }
    return out
}
