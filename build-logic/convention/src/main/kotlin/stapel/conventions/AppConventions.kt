/** `stapel.catalog`: `catalog/` → `stapel-catalog`, the version catalog a generated app imports. */
class CatalogPlugin : Plugin<Project> {
    override fun apply(target: Project) = with(target) {
        pluginManager.apply("base")
        pluginManager.apply("version-catalog")
        val ext = applyStapelBase(StapelFamily.CATALOG)
        ext.description.convention("Gradle version catalog for apps built on stapel-kmp: every stapel artifact at the train version, plus the toolchain pins.")
        applyStapelPublish(ext)
        extensions.configure(MavenPublishBaseExtension::class.java) { configure(VersionCatalog()) }
        val train = versionName(this)
        val groupName = mavenGroup(this)
        val versions = APP_VERSIONS.associateWith { catalogVersion(it) }
        val libraries = APP_LIBRARIES.mapValues { (alias, key) ->
            val dep = lib(alias).get()
            check(dep.versionConstraint.requiredVersion == versions[key]) { "catalog: $alias does not follow version '$key'" }
            Triple(dep.module.group, dep.module.name, key)
        }
        val plugins = APP_PLUGINS.mapValues { (alias, key) ->
            val p = libs.findPlugin(alias).orElseThrow { GradleException("Catalog has no plugin '$alias'") }.get()
            check(p.version.requiredVersion == versions[key]) { "catalog: plugin $alias does not follow version '$key'" }
            p.pluginId to key
        }
        val entries = mutableListOf<String>()
        val self = this
        gradle.projectsEvaluated {
            val rows = self.registryRows().map { it.split("|") }
            self.extensions.configure(CatalogPluginExtension::class.java) {
                versionCatalog {
                    version("stapel", train)
                    versions.forEach { (k, v) -> version(k, v) }
                    for (r in rows) {
                        val artifact = r[0]
                        val family = r[1]
                        if (family == "gradle-plugin") {
                            plugin("stapel-${r[6].substringAfterLast('.')}", r[6]).versionRef("stapel")
                        } else if (family != "catalog") {
                            library(artifact, groupName, artifact).versionRef("stapel")
                        }
                        entries += "$artifact|$family"
                    }
                    libraries.forEach { (alias, gnk) -> library(alias, gnk.first, gnk.second).versionRef(gnk.third) }
                    plugins.forEach { (alias, idk) -> plugin(alias, idk.first).versionRef(idk.second) }
                }
            }
        }
        val check = tasks.register("checkPublishedCatalog", CheckPublishedCatalog::class.java) {
            group = STAPEL_GATES
            description = "The published catalog carries no pre-release version and no consumer module."
            toml.set(layout.buildDirectory.file("version-catalog/libs.versions.toml"))
            stamp.set(layout.buildDirectory.file("stapel-gates/checkPublishedCatalog"))
            dependsOn("generateCatalogAsToml")
        }
        tasks.named("stapelCheckFast").configure { dependsOn(check) }
        pluginManager.withPlugin("lifecycle-base") { tasks.named("check").configure { dependsOn(check) } }
        Unit
    }
}

/** `checkPublishedCatalog`: no pre-release version, every stapel module a published feature module. */
abstract class CheckPublishedCatalog : DefaultTask() {
    /** The generated TOML. */
    @get:org.gradle.api.tasks.InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val toml: RegularFileProperty

    /** Stamp. */
    @get:OutputFile abstract val stamp: RegularFileProperty

    @TaskAction
    fun run() {
        val text = toml.get().asFile.readText()
        val bad = Regex("""=\s*"([^"]+)"""").findAll(text).map { it.groupValues[1] }.filter { isPreRelease(it) }.toList()
        val consumer = Regex("""stapel-[a-z0-9-]*-(e2e|demo)\b""").findAll(text).map { it.value }.toList()
        if (bad.isNotEmpty() || consumer.isNotEmpty()) {
            throw GradleException(
                "checkPublishedCatalog: pre-release versions $bad, consumer modules $consumer in the published catalog.",
            )
        }
        stamp.get().asFile.apply { parentFile.mkdirs() }.writeText("ok\n")
    }
}

