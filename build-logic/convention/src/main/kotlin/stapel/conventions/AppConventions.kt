internal fun registryFamily(f: StapelFamily): String = when (f) {
    StapelFamily.SUBSTRATE, StapelFamily.SUBSTRATE_UI -> "substrate"
    StapelFamily.CAPABILITY, StapelFamily.CAPABILITY_UI -> "capability"
    StapelFamily.BRICK_DOMAIN -> "brick-domain"
    StapelFamily.BRICK_UI -> "brick-ui"
    StapelFamily.BRICK_ADAPTER -> "brick-adapter"
    StapelFamily.BRICK_TESTING -> "brick-testing"
    StapelFamily.BOM -> "bom"
    StapelFamily.CATALOG -> "catalog"
    StapelFamily.GRADLE_PLUGIN -> "gradle-plugin"
    else -> error("$f is not published")
}

/** `artifactId|family|brick|descriptorFqn|descriptorPresent|manifestPath|pluginId` per published feature module. */
internal fun Project.registryRows(): List<String> = rootProject.subprojects
    .filter { it.extensions.extraProperties.has(FAMILY_PROPERTY) }
    .mapNotNull { p ->
        val f = StapelFamily.valueOf(p.extensions.extraProperties.get(FAMILY_PROPERTY).toString())
        if (!f.published || f.role != FamilyRole.FEATURE) return@mapNotNull null
        val artifact = if (f == StapelFamily.GRADLE_PLUGIN) gradlePluginArtifact(p) else p.name
        val brick = p.extensions.extraProperties.get(BRICK_PROPERTY).toString()
        val descriptor = if (f == StapelFamily.BRICK_UI) p.brickDescriptor() else ""
        val present = f == StapelFamily.BRICK_UI && p.brickDescriptorFile().isFile
        val manifest = if (f == StapelFamily.BRICK_UI) p.file(NAV_MANIFEST).absolutePath else ""
        val pluginId = if (f == StapelFamily.GRADLE_PLUGIN) gradlePluginId(p) else ""
        "$artifact|${registryFamily(f)}|$brick|$descriptor|$present|$manifest|$pluginId"
    }
    .sortedBy { it.substringBefore('|') }

/** `exportKmpRegistry` writes, `checkKmpRegistry` compares: the scaffold's view of this repository. */
abstract class KmpRegistryTask : DefaultTask() {
    /** Rows from [registryRows]. */
    @get:Input abstract val rows: ListProperty<String>

    /** Train version. */
    @get:Input abstract val train: Property<String>

    /** Maven group. */
    @get:Input abstract val mavenGroupName: Property<String>

    /** Artifacts released to the public repository (gradle/released-artifacts.txt). */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val released: ConfigurableFileCollection

    /** The committed nav-manifest.json files (inputs). */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val manifests: ConfigurableFileCollection

    /** kmp-registry.json at the root. */
    @get:Internal abstract val target: RegularFileProperty

    /** True = drift check, false = write. */
    @get:Input abstract val check: Property<Boolean>

    /** Stamp (check mode). */
    @get:OutputFile @get:Optional abstract val stamp: RegularFileProperty

    @TaskAction
    fun run() {
        val text = kmpRegistryJson(rows.get(), train.get(), mavenGroupName.get(), releasedSet())
        val file = target.get().asFile
        if (check.get()) {
            if (!file.isFile || file.readText() != text) {
                throw GradleException("checkKmpRegistry: kmp-registry.json is stale. Run ./gradlew exportKmpRegistry and commit it.")
            }
            stamp.get().asFile.apply { parentFile.mkdirs() }.writeText("ok\n")
        } else {
            file.writeText(text)
        }
    }

    private fun releasedSet(): Set<String> = released.files.filter { it.isFile }.flatMap { it.readLines() }
        .map { it.substringBefore('#').trim() }.filter { it.isNotEmpty() }.toSet()
}

@Suppress("UNCHECKED_CAST")
internal fun kmpRegistryJson(rows: List<String>, train: String, group: String, released: Set<String>): String {
    val artifacts = linkedMapOf<String, Any?>()
    val bricks = sortedMapOf<String, Any?>()
    val plugins = sortedMapOf<String, Any?>()
    val parsed = rows.map { it.split("|") }
    for ((artifact, family, _, _, _, _, _) in parsed.map { Row(it) }) {
        artifacts[artifact] = linkedMapOf("version" to train, "family" to family, "released" to (artifact in released))
    }
    for (r in parsed.map { Row(it) }) {
        if (r.family == "gradle-plugin") {
            plugins[r.pluginId.substringAfterLast('.')] = linkedMapOf("id" to r.pluginId, "artifact" to r.artifact, "version" to train)
        }
        if (r.family != "brick-ui") continue
        val mf = File(r.manifest)
        val manifest = if (mf.isFile) JsonSlurper().parse(mf) as Map<String, Any?> else null
        val destinations = (manifest?.get("destinations") as List<Map<String, Any?>>?).orEmpty()
        val embeds = (manifest?.get("embeds") as List<Map<String, Any?>>?).orEmpty()
        val testing = "stapel-${r.brick}-testing"
        bricks[r.brick] = linkedMapOf(
            "brick" to r.brick,
            "domain" to "stapel-${r.brick}".takeIf { it in artifacts },
            "ui" to r.artifact,
            "testing" to testing.takeIf { it in artifacts },
            "descriptor" to linkedMapOf(
                "class" to r.descriptor,
                "call" to "${r.descriptor}()",
                "present" to r.present,
            ),
            "entries" to destinations.map { it["id"] },
            "embeds" to embeds.map { it["id"] },
            "presentation" to destinations.associate { it["id"] to it["presentation"] }.toSortedMap(compareBy { it.toString() }),
            "requires" to destinations.associate { it["id"] to it["requires"] }.toSortedMap(compareBy { it.toString() }),
        )
    }
    val doc = linkedMapOf(
        "version" to 1,
        "train" to train,
        "group" to group,
        "bom" to "stapel-bom",
        "catalog" to "stapel-catalog".takeIf { it in artifacts },
        "app" to linkedMapOf(
            "artifact" to "stapel-app",
            "builder" to "stapel.app.di.stapelApp",
            "content" to "stapel.app.di.StapelAppContent",
            "brickInterface" to "stapel.app.di.StapelBrick",
            "offline" to linkedMapOf("artifact" to "stapel-cache-room", "module" to "stapel.cache.room.di.cacheRoomModule"),
        ),
        "plugins" to plugins,
        "artifacts" to artifacts,
        "bricks" to bricks,
    )
    return JsonOutput.prettyPrint(JsonOutput.toJson(doc)).replace("    ", "  ")
        .replace(Regex("""\{\s+\}"""), "{}").replace(Regex("""\[\s+\]"""), "[]") + "\n"
}

private class Row(p: List<String>) {
    val artifact = p[0]
    val family = p[1]
    val brick = p[2]
    val descriptor = p[3]
    val present = p[4].toBoolean()
    val manifest = p[5]
    val pluginId = p[6]
    operator fun component1() = artifact
    operator fun component2() = family
    operator fun component3() = brick
    operator fun component4() = descriptor
    operator fun component5() = present
    operator fun component6() = manifest
    operator fun component7() = pluginId
}

/** Paths of the brick UI libraries (the projects that own a `nav-manifest.json` and `exportNavManifest`). */
private fun Project.brickUiPaths(): List<String> = rootProject.subprojects
    .filter { it.extensions.extraProperties.has(FAMILY_PROPERTY) }
    .filter { StapelFamily.valueOf(it.extensions.extraProperties.get(FAMILY_PROPERTY).toString()) == StapelFamily.BRICK_UI }
    .map { it.path }

internal fun Project.registerKmpRegistryTasks() {
    fun KmpRegistryTask.common() {
        rows.set(provider { registryRows() })
        train.set(versionName(project))
        mavenGroupName.set(mavenGroup(project))
        released.from(file("gradle/released-artifacts.txt"))
        // Every brick UI library's manifest, present or not yet, and after its export when both run in one
        // invocation: the registry reads the manifests' entries.
        manifests.from(provider { brickUiPaths().map { rootProject.project(it).file(NAV_MANIFEST) } })
        mustRunAfter(provider { brickUiPaths().map { "$it:exportNavManifest" } })
        target.set(layout.projectDirectory.file("kmp-registry.json"))
    }
    tasks.register("exportKmpRegistry", KmpRegistryTask::class.java) {
        group = "stapel generate"
        description = "Writes kmp-registry.json: every published artifact and every brick's descriptor and nav ids."
        common()
        check.set(false)
        outputs.upToDateWhen { false }
    }
    val check = tasks.register("checkKmpRegistry", KmpRegistryTask::class.java) {
        group = STAPEL_GATES
        description = "kmp-registry.json equals what the build exports (drift gate)."
        common()
        check.set(true)
        inputs.file(layout.projectDirectory.file("kmp-registry.json")).optional()
        stamp.set(layout.buildDirectory.file("stapel-gates/checkKmpRegistry"))
    }
    tasks.named("check").configure { dependsOn(check) }
    tasks.named("stapelCheckFast").configure { dependsOn(check) }
}

