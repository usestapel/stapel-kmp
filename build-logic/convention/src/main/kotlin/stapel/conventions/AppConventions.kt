/** `tools/<a>/gradle-plugin` → the short name `<a>` without `-gen` (`codegen`, `tokens`). */
internal fun gradlePluginShortName(p: Project): String = p.path.split(':').filter { it.isNotEmpty() }[1].removeSuffix("-gen")

internal fun gradlePluginArtifact(p: Project): String = "stapel-${gradlePluginShortName(p)}-gradle-plugin"

internal fun gradlePluginId(p: Project): String = "${mavenGroup(p)}.${gradlePluginShortName(p)}"

/**
 * `stapel.gradle-plugin`: a published Gradle plugin for apps (`tools/<a>/gradle-plugin`). Plugin id
 * `<group>.<a>` (`io.github.usestapel.codegen`), artifact `stapel-<a>-gradle-plugin`. Unpublished tool
 * modules it needs are declared in `stapelBundled` and merged into its jar; their external
 * dependencies must be declared by the plugin module itself.
 */
class GradlePluginPlugin : Plugin<Project> {
    override fun apply(target: Project) = with(target) {
        val ext = applyStapelBase(StapelFamily.GRADLE_PLUGIN)
        applyJvmToolBasics()
        pluginManager.apply("java-gradle-plugin")
        applyStapelDepcheck(ext)
        val bundled = configurations.create("stapelBundled") {
            isCanBeConsumed = false
            isCanBeResolved = true
            isTransitive = false
        }
        configurations.named("compileOnly").configure { extendsFrom(bundled) }
        configurations.named("testImplementation").configure { extendsFrom(bundled) }
        val archives = serviceOf<org.gradle.api.file.ArchiveOperations>()
        tasks.named("jar", Jar::class.java).configure {
            from(bundled.elements.map { set -> set.map { if (it.asFile.isDirectory) it.asFile else archives.zipTree(it.asFile) } })
            duplicatesStrategy = org.gradle.api.file.DuplicatesStrategy.EXCLUDE
            exclude("META-INF/MANIFEST.MF")
        }
        tasks.withType(PluginUnderTestMetadata::class.java).configureEach { pluginClasspath.from(bundled) }
        val id = gradlePluginId(this)
        val artifact = gradlePluginArtifact(this)
        extensions.configure(GradlePluginDevelopmentExtension::class.java) {
            plugins.register("stapel${pascal(gradlePluginShortName(this@with))}") {
                this.id = id
                implementationClass = ext.pluginImplementationClass.orNull ?: "unset"
                displayName = artifact
                description = ext.description.orNull
            }
        }
        afterEvaluate {
            val impl = ext.pluginImplementationClass.orNull
                ?: throw GradleException("$path: stapel { pluginImplementationClass.set(\"…\") } is required for stapel.gradle-plugin")
            extensions.configure(GradlePluginDevelopmentExtension::class.java) {
                plugins.named("stapel${pascal(gradlePluginShortName(this@with))}").configure { implementationClass = impl }
            }
        }
        applyStapelPublish(ext, artifact)
        extensions.configure(MavenPublishBaseExtension::class.java) {
            configure(GradlePlugin(JavadocJar.Empty(), SourcesJar.Sources()))
        }
        Unit
    }
}
