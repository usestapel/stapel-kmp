    override fun apply(target: Project) = with(target) {
        val ext = applyLibrary(StapelFamily.BRICK_TESTING)
        val kmp = extensions.getByType(KotlinMultiplatformExtension::class.java)
        kmp.sourceSets.getByName("commonMain").dependencies {
            rootProject.findProject(":stapel-${ext.brick.get()}-ui")?.let { api(project(it.path)) }
            api(lib("compose-ui-test"))
        }
    }
}

