internal fun pascal(key: String): String =
    key.split('-', '_', '.').joinToString("") { part -> part.replaceFirstChar { it.uppercaseChar() } }

/** The `StapelBrick` descriptor a brick UI library exposes: `<pkg>.di.<Brick>Brick`. */
internal fun Project.brickDescriptor(): String = "${stapelNames().packageName}.di.${pascal(stapelNames().brick!!)}Brick"

internal fun Project.brickDescriptorFile(): File {
    val fqn = brickDescriptor()
    return file("src/commonMain/kotlin/" + fqn.replace('.', '/') + ".kt")
}

/** Generates `internal object <pkg>.generated.StapelBuildInfo` (group, artifact id, train version). */
internal fun Project.registerBuildInfo() {
    val names = stapelNames()
    val group = mavenGroup(this)
    val version = versionName(this)
    val out = layout.buildDirectory.dir("generated/stapelBuildInfo")
    val task = tasks.register("generateStapelBuildInfo") {
        description = "Writes <pkg>.generated.StapelBuildInfo (group, artifact id, train version)."
        inputs.property("coordinates", "$group:${names.artifactId}:$version")
        outputs.dir(out)
        doLast {
            val dir = out.get().asFile
            dir.deleteRecursively()
            val pkg = "${names.packageName}.generated"
            val f = File(dir, pkg.replace('.', '/') + "/StapelBuildInfo.kt")
            f.parentFile.mkdirs()
            f.writeText(
                "// Generated by the stapel build (VERSION_NAME, stapel.group). Do not edit.\n" +
                    "package $pkg\n\n" +
                    "/** Coordinates of this library as the build publishes it. */\n" +
                    "internal object StapelBuildInfo {\n" +
                    "    const val GROUP: String = \"$group\"\n" +
                    "    const val ARTIFACT_ID: String = \"${names.artifactId}\"\n" +
                    "    const val VERSION: String = \"$version\"\n" +
                    "}\n",
            )
        }
    }
    extensions.getByType(KotlinMultiplatformExtension::class.java).sourceSets.getByName("commonMain").kotlin.srcDir(task)
}

internal const val NAV_MANIFEST = "nav-manifest.json"
internal const val EXPORT_MAIN = "stapel.app.di.export.NavManifestExportKt"
internal const val COMPOSITION_DIR = "gradle/composition"

/**
 * `exportNavManifest` / `checkNavManifest` / `checkNavParity` on a brick UI library.
 *
 * - export: runs the library's `StapelBrick` descriptor on the JVM and writes `nav-manifest.json` at
 *   the module root (committed);
 * - check: the same into the build dir, byte-compared with the committed file (drift gate);
 * - parity: the committed file's shared fields against the pinned `composition-registry.json`.
 *
 * A brick UI library without a descriptor yet is reported, not failed, as long as it also has no
 * manifest; a descriptor without a committed manifest fails.
 */
internal fun Project.registerNavManifestTasks(ext: StapelExtension) {
    val names = stapelNames()
    val descriptor = brickDescriptor()
    val descriptorFile = brickDescriptorFile()
    val manifest = file(NAV_MANIFEST)
    val coordinates = "${mavenGroup(this)}:${names.artifactId}"
    val runtime = configurations.named("jvmRuntimeClasspath")
    val jar = tasks.named("jvmJar", Jar::class.java)
    fun JavaExec.common(out: File) {
        group = STAPEL_GATES
        classpath(jar, runtime)
        mainClass.set(EXPORT_MAIN)
        args(descriptor, coordinates, out.absolutePath)
        val present = descriptorFile.isFile
        onlyIf("needs the StapelBrick descriptor $descriptor") { present }
    }
    tasks.register("exportNavManifest", JavaExec::class.java) {
        description = "Writes nav-manifest.json from the library's StapelBrick descriptor (commit it)."
        common(manifest)
        group = "stapel generate"
    }
    val generated = layout.buildDirectory.file("stapel-nav/$NAV_MANIFEST")
    val check = tasks.register("checkNavManifest", JavaExec::class.java) {
        description = "nav-manifest.json equals what the StapelBrick descriptor exports (drift gate)."
        val out = generated.get().asFile
        common(out)
        val committed = manifest
        val desc = descriptor
        doFirst {
            if (!committed.isFile) {
                throw GradleException(
                    "checkNavManifest ($path): $desc exists but $NAV_MANIFEST is not committed. Run ./gradlew $path:exportNavManifest.",
                )
            }
        }
        doLast {
            if (out.readText() != committed.readText()) {
                throw GradleException(
                    "checkNavManifest ($path): $NAV_MANIFEST differs from what $desc exports. " +
                        "Run ./gradlew $path:exportNavManifest and commit the file.",
                )
            }
        }
    }
    val root = rootProject.layout.projectDirectory
    val parity = tasks.register("checkNavParity", CheckNavParity::class.java) {
        group = STAPEL_GATES
        description = "nav-manifest.json shared fields equal the pinned stapel-tools composition-registry.json."
        projectPath.set(path)
        brick.set(ext.brick)
        manifestFile.from(manifest)
        registry.from(root.file("$COMPOSITION_DIR/composition-registry.json"))
        pin.from(root.file("$COMPOSITION_DIR/pin.json"))
        stamp.set(layout.buildDirectory.file("stapel-gates/checkNavParity"))
    }
    tasks.named("stapelCheckFast").configure { dependsOn(check, parity) }
    pluginManager.withPlugin("lifecycle-base") { tasks.named("check").configure { dependsOn(check, parity) } }
}

internal fun sha256(bytes: ByteArray): String =
    MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

/** Reads `gradle/composition/pin.json` and verifies the vendored files' digests. */
internal fun verifiedComposition(pinFile: File): Map<String, Any?> {
    if (!pinFile.isFile) throw GradleException("$COMPOSITION_DIR/pin.json is missing (vendored stapel-tools composition data).")
    @Suppress("UNCHECKED_CAST")
    val pin = JsonSlurper().parse(pinFile) as Map<String, Any?>
    @Suppress("UNCHECKED_CAST")
    val files = pin["files"] as Map<String, Map<String, Any?>>
    val problems = files.mapNotNull { (rel, meta) ->
        val f = File(pinFile.parentFile, rel)
        when {
            !f.isFile -> "$rel is pinned but not vendored"
            sha256(f.readBytes()) != meta["sha256"] -> "$rel: sha256 ${sha256(f.readBytes())} != pinned ${meta["sha256"]}"
            else -> null
        }
    }
    if (problems.isNotEmpty()) {
        throw GradleException("$COMPOSITION_DIR does not match its pin.json:\n" + problems.joinToString("\n") { "  - $it" })
    }
    return pin
}

/** `checkNavParity`: a KMP manifest's shared fields equal the neutral registry entry of the same id. */
abstract class CheckNavParity : DefaultTask() {
    /** Project path, for messages. */
    @get:Input abstract val projectPath: Property<String>

    /** Brick key. */
    @get:Input abstract val brick: Property<String>

    /** The committed nav-manifest.json (may be absent). */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val manifestFile: ConfigurableFileCollection

    /** Vendored composition-registry.json. */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val registry: ConfigurableFileCollection

    /** Vendored pin.json. */
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val pin: ConfigurableFileCollection

    /** Stamp. */
    @get:OutputFile abstract val stamp: RegularFileProperty

    @TaskAction
    fun run() {
        val out = stamp.get().asFile.apply { parentFile.mkdirs() }
        val mf = manifestFile.files.firstOrNull { it.isFile }
        if (mf == null) {
            logger.lifecycle("checkNavParity (${projectPath.get()}): no $NAV_MANIFEST yet (no StapelBrick descriptor); nothing compared.")
            out.writeText("no manifest\n")
            return
        }
        verifiedComposition(pin.singleFile)
        @Suppress("UNCHECKED_CAST")
        val reg = JsonSlurper().parse(registry.singleFile) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val manifest = JsonSlurper().parse(mf) as Map<String, Any?>
        val errors = navParityErrors(reg, brick.get(), manifest)
        if (errors.isNotEmpty()) {
            throw GradleException(
                "checkNavParity (${projectPath.get()}) failed against the pinned composition-registry.json:\n" +
                    errors.joinToString("\n") { "  - $it" } +
                    "\nFix the library's NavContribution (ids, paths, placement, order, labels are shared with the web), " +
                    "or the registry in stapel-tools and re-pin $COMPOSITION_DIR.",
            )
        }
        out.writeText("ok\n")
    }
}

internal val SHARED_NAV_FIELDS = listOf(
    "labelKey", "icon", "path", "level", "parentId", "menuVisibleDefault", "requiresAuth", "surface", "order", "shortLabelKey",
)
internal val SHARED_EMBED_FIELDS = listOf("slot", "order", "surface", "opens", "scopeNavEntry", "routeProps", "breakpoints", "props")

/** Every difference between a KMP manifest and the neutral registry entry of its brick. */
@Suppress("UNCHECKED_CAST")
fun navParityErrors(registry: Map<String, Any?>, brick: String, manifest: Map<String, Any?>): List<String> {
    val errors = mutableListOf<String>()
    val bricks = registry["bricks"] as Map<String, Any?>
    val entry = bricks[brick] as Map<String, Any?>? ?: return listOf("brick '$brick' is unknown to the registry")
    val icons = (registry["icons"] as List<String>).toSet()
    val slots = (registry["slots"] as List<String>).toSet()
    val nav = (entry["nav"] as List<Map<String, Any?>>).associateBy { it["id"] as String }
    val embeds = (entry["embeds"] as List<Map<String, Any?>>).associateBy { it["id"] as String }
    for (d in manifest["destinations"] as List<Map<String, Any?>>) {
        val id = d["id"] as String
        val n = nav[id]
        if (n == null) {
            errors += "destination '$id' is unknown to the registry's '$brick' nav entries"
            continue
        }
        if (d["icon"] !in icons) errors += "destination '$id': icon '${d["icon"]}' is not in the neutral icon vocabulary"
        for (field in SHARED_NAV_FIELDS) {
            if (d[field] != n[field]) errors += "destination '$id': $field = ${d[field]} (KMP) != ${n[field]} (registry)"
        }
    }
    for (e in manifest["embeds"] as List<Map<String, Any?>>) {
        val id = e["id"] as String
        val n = embeds[id]
        if (n == null) {
            errors += "embed '$id' is unknown to the registry's '$brick' embeds"
            continue
        }
        if (e["slot"] !in slots) errors += "embed '$id': slot '${e["slot"]}' is not in the registry's slot vocabulary"
        for (field in SHARED_EMBED_FIELDS) {
            if (e[field] != n[field]) errors += "embed '$id': $field = ${e[field]} (KMP) != ${n[field]} (registry)"
        }
    }
    errors += kmpPlatformErrors(entry, manifest)
    return errors
}

/**
 * The registry's `platforms.kmp` block is what the scaffold's KMP emitter mounts: its artifact, entries
 * and embeds must be exactly what the library exports, or a generated app references a destination the
 * library lacks (or silently leaves one out). A brick without the block has no KMP pair yet.
 */
@Suppress("UNCHECKED_CAST")
internal fun kmpPlatformErrors(entry: Map<String, Any?>, manifest: Map<String, Any?>): List<String> {
    val kmp = (entry["platforms"] as Map<String, Any?>?)?.get("kmp") as Map<String, Any?>? ?: return emptyList()
    val errors = mutableListOf<String>()
    val artifactId = (manifest["artifact"] as String).substringAfterLast(':')
    if (kmp["ui"] != artifactId) errors += "platforms.kmp.ui = ${kmp["ui"]} (registry) != $artifactId (KMP manifest artifact)"
    fun compare(what: String, registryIds: Set<String>, libraryIds: Set<String>) {
        (registryIds - libraryIds).sorted().forEach { errors += "platforms.kmp.$what lists '$it', which the library does not export" }
        (libraryIds - registryIds).sorted().forEach { errors += "'$it' is exported but missing from the registry's platforms.kmp.$what" }
    }
    compare(
        "entries",
        (kmp["entries"] as List<String>).toSet(),
        (manifest["destinations"] as List<Map<String, Any?>>).map { it["id"] as String }.toSet(),
    )
    compare(
        "embeds",
        (kmp["embeds"] as List<String>).toSet(),
        (manifest["embeds"] as List<Map<String, Any?>>).map { it["id"] as String }.toSet(),
    )
    return errors
}

